// Generates neon/seed_orientation.sql from src/data/orientationCurriculum.ts,
// translated into Neon's live courses/modules/lessons schema (integer ids,
// modules.sort_order, lessons.body/minutes/sort_order).
// Usage: node --experimental-strip-types scripts/generate-orientation-neon-seed.mjs
import { writeFileSync } from 'node:fs';
import { ORIENTATION_CURRICULUM } from '../src/data/orientationCurriculum.ts';

const esc = (s) => String(s ?? '').replace(/'/g, "''");
const minutesFromDuration = (duration) => {
  const match = /(\d+)/.exec(duration || '');
  return match ? parseInt(match[1], 10) : 10;
};

const lines = [];
lines.push('-- ====================================================================');
lines.push('-- Beyond Barista Academy - Seed Orientation Course (0.1 - 0.14)');
lines.push('-- Generated by scripts/generate-orientation-neon-seed.mjs from');
lines.push('-- src/data/orientationCurriculum.ts - do not hand-edit, regenerate instead.');
lines.push('-- Matches the LIVE Neon schema (integer ids, sort_order, body, minutes).');
lines.push('--');
lines.push('-- Safe to re-run: re-running replaces this course\'s modules/lessons.');
lines.push('-- Run with: node scripts/run-sql-seed.mjs neon/seed_orientation.sql');
lines.push('-- ====================================================================');
lines.push('');
lines.push('DO $$');
lines.push('DECLARE');
lines.push('  v_course_id integer;');
lines.push('  v_mod_ids integer[] := \'{}\';');
lines.push('  v_mid integer;');
lines.push('BEGIN');
lines.push('  -- Ensure Orientation course exists');
lines.push('  INSERT INTO public.courses (slug, title, level, duration, description, image, price, instructor, capacity, status, created_at)');
lines.push('  VALUES (');
lines.push(`    'orientation-welcome-to-bba',`);
lines.push(`    'Orientation: Welcome to Beyond Barista Academy',`);
lines.push(`    'Beginner',`);
lines.push(`    '1 week',`);
lines.push(`    'Start here. Welcome message from Coach Egide, how the hybrid online academy works, learning rules, student code of conduct, assessment system, support, community, and graduation - required before starting any BBA program.',`);
lines.push(`    '/images/wood1.jpg',`);
lines.push(`    'Free',`);
lines.push(`    'Coach Egide HATEGEKIMANA',`);
lines.push(`    500,`);
lines.push(`    'active',`);
lines.push(`    to_char(now(), 'YYYY-MM-DD HH24:MI:SS')`);
lines.push('  )');
lines.push('  ON CONFLICT (slug) DO UPDATE SET title = EXCLUDED.title, description = EXCLUDED.description');
lines.push('  RETURNING id INTO v_course_id;');
lines.push('');
lines.push('  -- Clear any previous modules for this course (cascades to lessons) so this script is idempotent');
lines.push('  DELETE FROM public.modules WHERE course_id = v_course_id;');
lines.push('');

ORIENTATION_CURRICULUM.forEach((mod, i) => {
  lines.push(`  INSERT INTO public.modules (course_id, title, sort_order) VALUES (v_course_id, '${esc(mod.title)}', ${i + 1}) RETURNING id INTO v_mid; v_mod_ids := array_append(v_mod_ids, v_mid);`);
});

lines.push('');
lines.push('  INSERT INTO public.lessons (module_id, title, body, video_url, minutes, sort_order) VALUES');

const lessonRows = [];
ORIENTATION_CURRICULUM.forEach((mod, mIdx) => {
  mod.lessons.forEach((lesson, lIdx) => {
    lessonRows.push(
      `    (v_mod_ids[${mIdx + 1}], '${esc(lesson.title)}', '${esc(lesson.content)}', '${esc(lesson.videoUrl || '')}', ${minutesFromDuration(lesson.duration)}, ${lIdx + 1})`
    );
  });
});
lines.push(lessonRows.join(',\n') + ';');
lines.push('END $$;');
lines.push('');

writeFileSync(new URL('../neon/seed_orientation.sql', import.meta.url), lines.join('\n'), 'utf8');
console.log('Wrote neon/seed_orientation.sql');
