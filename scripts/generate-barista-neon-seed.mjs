// Generates neon/seed_barista_24_module.sql from src/data/baristaCurriculum.ts,
// translated into Neon's live courses/modules/lessons schema (integer ids,
// modules.sort_order, lessons.body/minutes/sort_order).
// Usage: node --experimental-strip-types scripts/generate-barista-neon-seed.mjs
import { writeFileSync } from 'node:fs';
import { BARISTA_CURRICULUM } from '../src/data/baristaCurriculum.ts';

const esc = (s) => String(s ?? '').replace(/'/g, "''");
const minutesFromDuration = (duration) => {
  const match = /(\d+)/.exec(duration || '');
  return match ? parseInt(match[1], 10) : 15;
};

const lines = [];
lines.push('-- ====================================================================');
lines.push('-- Beyond Barista Academy - Seed 24-Module Barista Curriculum into Neon');
lines.push('-- Generated by scripts/generate-barista-neon-seed.mjs from');
lines.push('-- src/data/baristaCurriculum.ts - do not hand-edit, regenerate instead.');
lines.push('-- Matches the LIVE Neon schema (integer ids, sort_order, body, minutes).');
lines.push('-- Added alongside the existing 23-course catalog, not replacing it.');
lines.push('-- ====================================================================');
lines.push('');
lines.push('DO $$');
lines.push('DECLARE');
lines.push('  v_course_id integer;');
lines.push('  v_mod_ids integer[] := \'{}\';');
lines.push('  v_mid integer;');
lines.push('BEGIN');
lines.push(`  INSERT INTO public.courses (slug, title, level, duration, description, image, price, instructor, capacity, status, created_at)`);
lines.push(`  VALUES (`);
lines.push(`    'professional-barista-mastery-24-module',`);
lines.push(`    'Professional Barista Mastery & Coffee Ecosystem (24 Modules + Certification)',`);
lines.push(`    'Advanced',`);
lines.push(`    '24 weeks',`);
lines.push(`    'The complete 24-module professional barista program from bean origin to roasting, brewing, sensory skills, hospitality management, and entrepreneurship, plus a final certification exam.',`);
lines.push(`    '/images/barista.jpg',`);
lines.push(`    'Free',`);
lines.push(`    'Coach Egide HATEGEKIMANA',`);
lines.push(`    500,`);
lines.push(`    'active',`);
lines.push(`    to_char(now(), 'YYYY-MM-DD HH24:MI:SS')`);
lines.push(`  )`);
lines.push(`  ON CONFLICT (slug) DO UPDATE SET title = EXCLUDED.title, description = EXCLUDED.description`);
lines.push(`  RETURNING id INTO v_course_id;`);
lines.push('');
lines.push('  -- Clear any previous modules for this course (cascades to lessons) so this script is idempotent');
lines.push('  DELETE FROM public.modules WHERE course_id = v_course_id;');
lines.push('');

BARISTA_CURRICULUM.forEach((mod, i) => {
  lines.push(`  INSERT INTO public.modules (course_id, title, sort_order) VALUES (v_course_id, '${esc(mod.title)}', ${i + 1}) RETURNING id INTO v_mid; v_mod_ids := array_append(v_mod_ids, v_mid);`);
});

lines.push('');
lines.push('  INSERT INTO public.lessons (module_id, title, body, video_url, minutes, sort_order) VALUES');

const lessonRows = [];
BARISTA_CURRICULUM.forEach((mod, mIdx) => {
  mod.lessons.forEach((lesson, lIdx) => {
    lessonRows.push(
      `    (v_mod_ids[${mIdx + 1}], '${esc(lesson.title)}', '${esc(lesson.content)}', '${esc(lesson.videoUrl || '')}', ${minutesFromDuration(lesson.duration)}, ${lIdx + 1})`
    );
  });
});
lines.push(lessonRows.join(',\n') + ';');
lines.push('END $$;');
lines.push('');

writeFileSync(new URL('../neon/seed_barista_24_module.sql', import.meta.url), lines.join('\n'), 'utf8');
console.log('Wrote neon/seed_barista_24_module.sql');
